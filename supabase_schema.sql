-- Run in Supabase SQL Editor.
-- Store job metadata only; do not store original uploads.
create table if not exists public.masking_jobs (
  id bigint generated by default as identity primary key,
  job_id text not null unique,
  original_filename text not null,
  output_filename text not null,
  file_type text not null,
  detected_count integer not null default 0,
  detected_types text[] not null default '{}',
  mask_mode text not null,
  storage_path text,
  created_at timestamptz not null default now()
);
alter table public.masking_jobs enable row level security;
-- Intentionally no anon/authenticated policies: browser users cannot read or write job history.
-- Flask writes with service-role key server-side only. Service-role key bypasses RLS and must remain secret.

insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('masked-files', 'masked-files', false, 26214400,
  array['text/plain','text/csv','application/pdf','application/vnd.openxmlformats-officedocument.wordprocessingml.document',
  'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet','application/json','text/markdown',
  'application/octet-stream'])
on conflict (id) do nothing;
-- Keep the bucket private. Server-side service role uploads masked output.
